# ─── Main dispatch ────────────────────────────────────────────────────────────

case "$MODE" in
  capture)
    echo "📡 Capturing Go clusters..."

    if ! command -v go &> /dev/null; then
      echo "⚠️  Go is not installed. Install Go to use the Go stack."
      echo "   See references/go.md for the Go capture protocol."
      exit 0
    fi

    CLUSTERS_JSON=$(read_go_clusters)

    if [ "$CLUSTERS_JSON" = "[]" ]; then
      echo "No Go clusters found in manifest."
      exit 0
    fi

    echo "Found Go clusters:"
    echo "$CLUSTERS_JSON" | node -e "
      const clusters = JSON.parse(require('fs').readFileSync('/dev/stdin', 'utf8'));
      clusters.forEach(c => console.log('  - ' + c.id + ' (' + c.entry + ')'));
    "

    # Generate helpers + test file
    HELPERS_FILE=$(generate_helpers_file)
    TEST_FILE=$(generate_capture_test "$CLUSTERS_JSON")
    echo "📄 Generated: $TEST_FILE"

    # Remove any stale validate test file (avoid package conflicts)
    rm -f "${REGRET_DIR}/regret_validate_test.go"

    echo "🔧 Building Go modules..."
    go build ./... 2>&1 || true

    echo "🧪 Running regret capture..."
    if go test -v -run TestRegretCapture "$REGRET_DIR" 2>&1; then
      echo ""
      echo "──────────────────────────────────────────────────"
      echo "Capture complete."
      echo ""
      echo "Next: bash scripts/capture_go.sh validate"
      echo "If all green → you are clear to refactor."
    else
      echo ""
      echo "⚠️  Go test execution failed."
      echo "   Check the test output above for compilation or runtime errors."
      echo "   Common issues:"
      echo "     - Package path mismatch (check goPackage field in manifest)"
      echo "     - Entry function not exported (must start with uppercase letter)"
      echo "     - go.mod not in project root"
      echo "     - For 'main' package: ensure there's a main() function"
      exit 1
    fi
    ;;

  validate)
    echo "🔍 Validating Go clusters..."

    if ! command -v go &> /dev/null; then
      echo "⚠️  Go is not installed. Cannot validate Go clusters."
      exit 0
    fi

    CLUSTERS_JSON=$(read_go_clusters)

    if [ "$CLUSTERS_JSON" = "[]" ]; then
      echo "No Go clusters found in manifest."
      exit 0
    fi

    HELPERS_FILE=$(generate_helpers_file)
    TEST_FILE=$(generate_validate_test "$CLUSTERS_JSON")
    echo "📄 Generated: $TEST_FILE"

    # Remove stale capture test file
    rm -f "${REGRET_DIR}/regret_capture_test.go"

    echo "🧪 Running regret validation..."
    if go test -v -run TestRegretValidate "$REGRET_DIR" 2>&1; then
      echo ""
      echo "────────────────────────────────────────────────────"
      echo "✅ All Go clusters validated — refactor is safe."
    else
      echo ""
      echo "────────────────────────────────────────────────────"
      echo "❌ Validation FAILED — fix the CODE, do not edit .regret files."
      echo "   Re-run: bash scripts/capture_go.sh validate"
      exit 1
    fi
    ;;

  health)
    node "$SKILL_DIR/scripts/health.js"
    ;;

  *)
    echo "Usage: bash scripts/capture_go.sh [capture|validate|health] [--cluster <id>]"
    echo ""
    echo "Default mode is 'capture' if no mode is specified."
    echo ""
    echo "Examples:"
    echo "  bash scripts/capture_go.sh                    # capture all Go clusters"
    echo "  bash scripts/capture_go.sh validate           # validate all Go clusters"
    echo "  bash scripts/capture_go.sh --cluster to-valid-bf   # capture single cluster"
    exit 1
    ;;
esac
