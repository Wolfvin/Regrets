#!/usr/bin/env bash
# capture_go.sh — compile + run regret capture/validate for Go clusters
#
# Generates Go test files from manifest.json, runs `go test`, and writes
# .regret files (capture) or compares fingerprints (validate).
#
# Usage:
#   bash scripts/capture_go.sh                # capture all Go clusters
#   bash scripts/capture_go.sh capture        # capture (explicit)
#   bash scripts/capture_go.sh validate       # validate all Go clusters
#   bash scripts/capture_go.sh health         # health report (delegates to health.js)
#   bash scripts/capture_go.sh --cluster to-valid-bf   # single-cluster capture
#
# .regret file format (identical to JS/Python stacks):
#   cluster: <id>
#   version: 1
#   fingerprint: <7char-base36>
#   captured: <ISO8601>
#   entry: <entry-fn-name>
#   stack: go
#   fingerprintLevel: entry
#   ---
#   INPUT  <json>
#   OUTPUT <json>
#   HASH   <7char-base36>

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SKILL_DIR="$(dirname "$SCRIPT_DIR")"
PROJECT_DIR="$(pwd)"
MANIFEST="${PROJECT_DIR}/regrets/manifest.json"
REGRET_DIR="${PROJECT_DIR}/regrets"

mkdir -p "$REGRET_DIR"

# Parse args. MODE is the first non-flag argument (defaults to "capture").
# --cluster <id> sets the cluster filter (works with or without explicit MODE).
MODE="capture"
CLUSTER_FILTER=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    --cluster)
      CLUSTER_FILTER="$2"
      shift 2
      ;;
    capture|validate|health)
      MODE="$1"
      shift
      ;;
    *)
      # Unknown arg — skip (could be a stale arg from older usage)
      shift
      ;;
  esac
done

# ─── Helper: emit the shared fingerprint + reflect helpers file ────────────────
# This file is written once per capture/validate run and shared by both the
# capture and validate test files. Keeping it separate avoids import-block
# conflicts (the fingerprint code has its own imports that would otherwise
# collide with the test file's imports).

generate_helpers_file() {
  local helpers_file="${REGRET_DIR}/regret_helpers_test.go"
  cat > "$helpers_file" << 'HELPERSEOF'
// regret_helpers_test.go — auto-generated by capture_go.sh
// DO NOT EDIT — shared fingerprint + reflect helpers for capture/validate tests.
package regrettest

import (
        "crypto/sha256"
        "encoding/json"
        "fmt"
        "math"
        "math/big"
        "reflect"
        "sort"
)

// stableStringify produces a deterministic JSON string with sorted keys.
// Must produce identical output to JS stableStringify() and Python stable_dumps().
//
// Edge cases that must match the JS implementation (issue #322):
//   - NaN → "__nan__" sentinel (JSON.stringify would emit "null")
//   - +Inf → "__infinity__"
//   - -Inf → "__neg_infinity__"
func stableStringify(obj interface{}) string {
        return doStableStringify(obj)
}

func doStableStringify(obj interface{}) string {
        if obj == nil {
                return "null"
        }
        switch v := obj.(type) {
        case bool:
                if v {
                        return "true"
                }
                return "false"
        case int:
                return fmt.Sprintf("%d", v)
        case int64:
                return fmt.Sprintf("%d", v)
        case float64:
                if v != v { // NaN
                        return "\"__nan__\""
                }
                if math.IsInf(v, 1) { // +Inf
                        return "\"__infinity__\""
                }
                if math.IsInf(v, -1) { // -Inf
                        return "\"__neg_infinity__\""
                }
                return fmt.Sprintf("%g", v)
        case string:
                b, _ := json.Marshal(v)
                return string(b)
        case []interface{}:
                parts := make([]string, len(v))
                for i, item := range v {
                        parts[i] = doStableStringify(item)
                }
                return "[" + joinStrings(parts, ",") + "]"
        case map[string]interface{}:
                keys := make([]string, 0, len(v))
                for k := range v {
                        keys = append(keys, k)
                }
                sort.Strings(keys)
                parts := make([]string, len(keys))
                for i, k := range keys {
                        b, _ := json.Marshal(k)
                        parts[i] = string(b) + ":" + doStableStringify(v[k])
                }
                return "{" + joinStrings(parts, ",") + "}"
        default:
                b, _ := json.Marshal(v)
                return string(b)
        }
}

func joinStrings(ss []string, sep string) string {
        result := ""
        for i, s := range ss {
                if i > 0 {
                        result += sep
                }
                result += s
        }
        return result
}

// fingerprint computes the 7-char base36 hash.
// Must match JS fingerprint(): sha256(stableStringify(input) + "|" + stableStringify(output)) → base36 → first 7 chars
func fingerprint(input interface{}, output interface{}) string {
        combined := stableStringify(input) + "|" + stableStringify(output)
        hash := sha256.Sum256([]byte(combined))
        hexStr := fmt.Sprintf("%x", hash)
        bigNum := new(big.Int)
        bigNum.SetString(hexStr, 16)
        b36 := toBase36(bigNum)
        if len(b36) >= 7 {
                return b36[:7]
        }
        return b36
}

func toBase36(n *big.Int) string {
        if n.Sign() == 0 {
                return "0"
        }
        abs := new(big.Int).Set(n)
        if abs.Sign() < 0 {
                abs.Abs(abs)
        }
        base := big.NewInt(36)
        digits := ""
        for abs.Sign() > 0 {
                mod := new(big.Int)
                abs.DivMod(abs, base, mod)
                digits = string(base36Digit(mod.Int64())) + digits
        }
        return digits
}

func base36Digit(d int64) byte {
        if d < 10 {
                return byte('0' + d)
        }
        return byte('a' + d - 10)
}

// invokeEntry calls a Go function via reflection.
//   - input == nil → zero-arg call
//   - multiArgs=true → input must be []interface{}, each element becomes one arg
//   - multiArgs=false → input is the sole arg
// Returns the first result. If the last result is a non-nil error, returns it.
func invokeEntry(fn reflect.Value, input interface{}, multiArgs bool) (interface{}, error) {
        var args []reflect.Value
        if input == nil {
                // zero-arg call
        } else if multiArgs {
                arr, ok := input.([]interface{})
                if !ok {
                        return nil, fmt.Errorf("multiArgs=true but input is not array: %T", input)
                }
                fnType := fn.Type()
                if len(arr) != fnType.NumIn() {
                        return nil, fmt.Errorf("multiArgs: input has %d elements but function takes %d args", len(arr), fnType.NumIn())
                }
                for i, a := range arr {
                        conv, err := convertArg(a, fnType.In(i))
                        if err != nil {
                                return nil, err
                        }
                        args = append(args, conv)
                }
        } else {
                fnType := fn.Type()
                if fnType.NumIn() > 0 {
                        conv, err := convertArg(input, fnType.In(0))
                        if err != nil {
                                return nil, err
                        }
                        args = append(args, conv)
                }
        }
        results := fn.Call(args)
        if len(results) == 0 {
                return nil, nil
        }
        last := results[len(results)-1]
        if err, ok := last.Interface().(error); ok && err != nil {
                return nil, err
        }
        return results[0].Interface(), nil
}

// convertArg converts a JSON-decoded interface{} value to the expected Go type.
// JSON numbers come back as float64; we convert to int/int64/float64 as needed.
func convertArg(val interface{}, expected reflect.Type) (reflect.Value, error) {
        if val == nil {
                return reflect.Zero(expected), nil
        }
        valType := reflect.TypeOf(val)
        if valType == expected {
                return reflect.ValueOf(val), nil
        }
        switch expected.Kind() {
        case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
                if f, ok := val.(float64); ok {
                        return reflect.ValueOf(f).Convert(expected), nil
                }
        case reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
                if f, ok := val.(float64); ok {
                        return reflect.ValueOf(f).Convert(expected), nil
                }
        case reflect.Float32, reflect.Float64:
                if f, ok := val.(float64); ok {
                        return reflect.ValueOf(f).Convert(expected), nil
                }
        case reflect.String:
                if s, ok := val.(string); ok {
                        return reflect.ValueOf(s), nil
                }
        case reflect.Bool:
                if b, ok := val.(bool); ok {
                        return reflect.ValueOf(b), nil
                }
        case reflect.Slice:
                if arr, ok := val.([]interface{}); ok {
                        slice := reflect.MakeSlice(expected, 0, len(arr))
                        for _, item := range arr {
                                conv, err := convertArg(item, expected.Elem())
                                if err != nil {
                                        return reflect.Value{}, err
                                }
                                slice = reflect.Append(slice, conv)
                        }
                        return slice, nil
                }
        }
        if valType.ConvertibleTo(expected) {
                return reflect.ValueOf(val).Convert(expected), nil
        }
        return reflect.Value{}, fmt.Errorf("cannot convert %T to %v", val, expected)
}

// parseRegretFile extracts the INPUT and HASH lines from a .regret file.
// Returns (inputJSON, goldenHash, error).
func parseRegretFile(content string) (string, string, error) {
        var savedInputJSON, goldenHash string
        for _, line := range splitLines(content) {
                trimmed := line
                if hasPrefix(trimmed, "INPUT  ") {
                        savedInputJSON = trimmed[7:]
                } else if hasPrefix(trimmed, "HASH   ") {
                        goldenHash = trimmed[7:]
                }
        }
        if goldenHash == "" {
                return "", "", fmt.Errorf(".regret file has no HASH line")
        }
        return savedInputJSON, goldenHash, nil
}

func splitLines(s string) []string {
        var lines []string
        current := ""
        for _, ch := range s {
                if ch == '\n' {
                        lines = append(lines, current)
                        current = ""
                } else {
                        current += string(ch)
                }
        }
        if current != "" {
                lines = append(lines, current)
        }
        return lines
}

func hasPrefix(s, prefix string) bool {
        if len(s) < len(prefix) {
                return false
        }
        return s[:len(prefix)] == prefix
}
HELPERSEOF
  echo "$helpers_file"
}

# ─── Helper: Read Go clusters from manifest ───────────────────────────────────

read_go_clusters() {
  if [ ! -f "$MANIFEST" ]; then
    echo "❌ regrets/manifest.json not found"
    exit 1
  fi
  FILTER="$CLUSTER_FILTER" node -e "
    const m = JSON.parse(require('fs').readFileSync('$MANIFEST', 'utf8'));
    let clusters = m.clusters.filter(c => c.stack === 'go');
    const filter = process.env.FILTER || '';
    if (filter) {
      clusters = clusters.filter(c => c.id === filter);
    }
    console.log(JSON.stringify(clusters));
  "
}

# ─── Helper: compute unique package imports + alias map ──────────────────────
# Outputs Go import lines (one per line) and writes the alias map to a temp
# file for the test generator to read.
emit_imports_and_alias_map() {
  local clusters_json="$1"
  echo "$clusters_json" | node -e "
    const clusters = JSON.parse(require('fs').readFileSync('/dev/stdin', 'utf8'));
    const aliasMap = {};
    const uniquePkgs = [];
    for (const cluster of clusters) {
      const pkg = cluster.goPackage || 'main';
      if (!aliasMap[pkg]) {
        let alias = pkg.split('/').pop().replace(/[^a-zA-Z0-9_]/g, '_');
        if (!alias || /^[0-9]/.test(alias)) alias = 'pkg_' + alias;
        // Go reserves 'main' as a package name — use a different alias
        if (alias === 'main') alias = 'mainpkg';
        aliasMap[pkg] = alias;
        uniquePkgs.push({ pkg, alias });
      }
    }
    // Emit import lines
    for (const { pkg, alias } of uniquePkgs) {
      console.log('  ' + alias + ' \"' + pkg + '\"');
    }
    // Write alias map to stderr for the caller to capture (single JSON line)
    process.stderr.write(JSON.stringify(aliasMap));
  "
}

