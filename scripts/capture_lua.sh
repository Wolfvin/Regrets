#!/usr/bin/env bash
# capture_lua.sh — capture + validate for Lua clusters
#
# Generates a Lua runner script from manifest.json, runs the Lua interpreter,
# and writes .regret files (capture) or compares fingerprints (validate).
#
# Usage:
#   bash scripts/capture_lua.sh                # capture all Lua clusters
#   bash scripts/capture_lua.sh capture        # capture (explicit)
#   bash scripts/capture_lua.sh validate       # validate all Lua clusters
#   bash scripts/capture_lua.sh health         # health report (delegates to health.js)
#   bash scripts/capture_lua.sh --cluster my-fn   # single-cluster capture
#
# .regret file format (identical to JS/Python/Go stacks):
#   cluster: <id>
#   version: 1
#   fingerprint: <7char-base36>
#   captured: <ISO8601>
#   entry: <entry-fn-name>
#   stack: lua
#   fingerprintLevel: entry
#   ---
#   INPUT  <json>
#   OUTPUT <json>
#   HASH   <7char-base36>

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SKILL_DIR="$(dirname "$SCRIPT_DIR")"
PROJECT_DIR="$(pwd)"
MANIFEST="${PROJECT_DIR}/regrets/manifest.json"
REGRET_DIR="${PROJECT_DIR}/regrets"

mkdir -p "$REGRET_DIR"

# Parse args. MODE is the first non-flag argument (defaults to "capture").
# --cluster <id> sets the cluster filter.
MODE="capture"
CLUSTER_FILTER=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    --cluster)
      CLUSTER_FILTER="$2"
      shift 2
      ;;
    capture|validate|health)
      MODE="$1"
      shift
      ;;
    *)
      shift
      ;;
  esac
done

# ─── Helper: locate the Lua interpreter ───────────────────────────────────────
# Priority:
#   1. $LUA_INTERPRETER env var (if set)
#   2. `lua` on PATH
#   3. `lua5.4` on PATH
#   4. `/tmp/lua-5.4.7/src/lua` (built from source — see verify script)
LUA_BIN="${LUA_INTERPRETER:-}"
if [ -z "$LUA_BIN" ]; then
  if command -v lua &> /dev/null; then
    LUA_BIN="lua"
  elif command -v lua5.4 &> /dev/null; then
    LUA_BIN="lua5.4"
  elif [ -x "/tmp/lua-5.4.7/src/lua" ]; then
    LUA_BIN="/tmp/lua-5.4.7/src/lua"
  else
    echo "❌ Lua interpreter not found."
    echo "   Install Lua (e.g. 'apt install lua5.4' or build from source: https://www.lua.org/ftp/lua-5.4.7.tar.gz)"
    echo "   Or set LUA_INTERPRETER=/path/to/lua"
    exit 1
  fi
fi

# ─── Helper: Read Lua clusters from manifest ──────────────────────────────────

read_lua_clusters() {
  if [ ! -f "$MANIFEST" ]; then
    echo "❌ regrets/manifest.json not found"
    exit 1
  fi
  FILTER="$CLUSTER_FILTER" node -e "
    const m = JSON.parse(require('fs').readFileSync('$MANIFEST', 'utf8'));
    let clusters = m.clusters.filter(c => c.stack === 'lua');
    const filter = process.env.FILTER || '';
    if (filter) {
      clusters = clusters.filter(c => c.id === filter);
    }
    console.log(JSON.stringify(clusters));
  "
}

# ─── Main dispatch ────────────────────────────────────────────────────────────

case "$MODE" in
  capture)
    echo "📡 Capturing Lua clusters..."

    CLUSTERS_JSON=$(read_lua_clusters)

    if [ "$CLUSTERS_JSON" = "[]" ]; then
      echo "No Lua clusters found in manifest."
      exit 0
    fi

    echo "Found Lua clusters:"
    echo "$CLUSTERS_JSON" | node -e "
      const clusters = JSON.parse(require('fs').readFileSync('/dev/stdin', 'utf8'));
      clusters.forEach(c => console.log('  - ' + c.id + ' (' + c.entry + ')'));
    "

    # Generate the Lua runner script that does the capture
    RUNNER="${REGRET_DIR}/regret_capture.lua"
    cat > "$RUNNER" << 'LUAEOF'
