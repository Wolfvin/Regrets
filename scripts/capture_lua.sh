    0x391c0cb3, 0x4ed8aa4a, 0x5b9cca4f, 0x682e6ff3,
    0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208,
    0x90befffa, 0xa4506ceb, 0xbef9a3f7, 0xc67178f2,
  }

  local function tobytes(s)
    local bytes = {}
    for i = 1, #s do
      bytes[i] = s:byte(i)
    end
    return bytes
  end

  local function sha256_hex(s)
    local h = {table.unpack(H)}
    local bytes = tobytes(s)
    local bit_len = #bytes * 8
    bytes[#bytes + 1] = 0x80
    while (#bytes % 64) ~= 56 do
      bytes[#bytes + 1] = 0
    end
    for i = 1, 4 do
      bytes[#bytes + 1] = 0  -- high 32 bits of length
    end
    for i = 4, 1, -1 do
      bytes[#bytes + 1] = (bit_len >> (8 * (i - 1))) & 0xFF  -- low 32 bits
    end

    for chunk_start = 1, #bytes, 64 do
      local w = {}
      for i = 0, 15 do
        local offset = chunk_start + i * 4
        w[i + 1] = (bytes[offset] << 24) | (bytes[offset + 1] << 16) | (bytes[offset + 2] << 8) | bytes[offset + 3]
        w[i + 1] = w[i + 1] & 0xFFFFFFFF
      end
      for i = 17, 64 do
        local s0 = rrotate(w[i - 15], 7) ~ rrotate(w[i - 15], 18) ~ (w[i - 15] >> 3)
        local s1 = rrotate(w[i - 2], 17) ~ rrotate(w[i - 2], 19) ~ (w[i - 2] >> 10)
        w[i] = (w[i - 16] + s0 + w[i - 7] + s1) & 0xFFFFFFFF
      end

      local a, b, c, d, e, f, g, hh = h[1], h[2], h[3], h[4], h[5], h[6], h[7], h[8]

      for i = 1, 64 do
        local s1 = rrotate(e, 6) ~ rrotate(e, 11) ~ rrotate(e, 25)
        local ch = (e & f) ~ ((~e & 0xFFFFFFFF) & g)
        local temp1 = (hh + s1 + ch + K[i] + w[i]) & 0xFFFFFFFF
        local s0 = rrotate(a, 2) ~ rrotate(a, 13) ~ rrotate(a, 22)
        local maj = (a & b) ~ (a & c) ~ (b & c)
        local temp2 = (s0 + maj) & 0xFFFFFFFF

        hh = g
        g = f
        f = e
        e = (d + temp1) & 0xFFFFFFFF
        d = c
        c = b
        b = a
        a = (temp1 + temp2) & 0xFFFFFFFF
      end

      h[1] = (h[1] + a) & 0xFFFFFFFF
      h[2] = (h[2] + b) & 0xFFFFFFFF
      h[3] = (h[3] + c) & 0xFFFFFFFF
      h[4] = (h[4] + d) & 0xFFFFFFFF
      h[5] = (h[5] + e) & 0xFFFFFFFF
      h[6] = (h[6] + f) & 0xFFFFFFFF
      h[7] = (h[7] + g) & 0xFFFFFFFF
      h[8] = (h[8] + hh) & 0xFFFFFFFF
    end

    local result = {}
    for i = 1, 8 do
      result[i] = string.format("%08x", h[i])
    end
    return table.concat(result)
  end

  return {
    sha256_hex = sha256_hex,
  }
end)()

-- ─── base36 (same as capture) ────────────────────────────────────────────────
local bigint = {}

function bigint.from_hex(hex)
  local limbs = {}
  local i = #hex
  while i > 0 do
    local start = math.max(1, i - 7)
    local chunk = hex:sub(start, i)
    limbs[#limbs + 1] = tonumber(chunk, 16)
    i = start - 1
  end
  return limbs
end

function bigint.divmod_small(limbs, divisor)
  local quotient = {}
  local remainder = 0
  for i = #limbs, 1, -1 do
    local combined = remainder * 4294967296 + limbs[i]
    local q = combined // divisor
    remainder = combined % divisor
    quotient[i] = q
  end
  while #quotient > 1 and quotient[#quotient] == 0 do
    quotient[#quotient] = nil
  end
  return quotient, remainder
end

function bigint.to_base36(limbs)
  if #limbs == 1 and limbs[1] == 0 then return "0" end
  local digits = {}
  local work = limbs
  while not (#work == 1 and work[1] == 0) do
    local remainder
    work, remainder = bigint.divmod_small(work, 36)
    local ch
    if remainder < 10 then
      ch = string.char(48 + remainder)
    else
      ch = string.char(97 + remainder - 10)
    end
    digits[#digits + 1] = ch
  end
  for i = 1, #digits // 2 do
    digits[i], digits[#digits - i + 1] = digits[#digits - i + 1], digits[i]
  end
  return table.concat(digits)
end

local function fingerprint(input, output)
  local combined = stable_stringify(input) .. "|" .. stable_stringify(output)
  local hash_hex = sha256.sha256_hex(combined)
  local limbs = bigint.from_hex(hash_hex)
  local b36 = bigint.to_base36(limbs)
  if #b36 >= 7 then
    return b36:sub(1, 7)
  end
  return b36
end

