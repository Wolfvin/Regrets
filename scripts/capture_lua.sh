local function skip_whitespace(s, i)
  while i <= #s and (s:sub(i,i) == " " or s:sub(i,i) == "\t" or s:sub(i,i) == "\n" or s:sub(i,i) == "\r") do
    i = i + 1
  end
  return i
end

local function parse_value(s, i)
  i = skip_whitespace(s, i)
  local c = s:sub(i, i)
  if c == "{" then return json.parse_object(s, i)
  elseif c == "[" then return json.parse_array(s, i)
  elseif c == "\"" then return json.parse_string(s, i)
  elseif c == "t" or c == "f" then return json.parse_bool(s, i)
  elseif c == "n" then return json.parse_null(s, i)
  elseif c == "-" or c:match("[0-9]") then return json.parse_number(s, i)
  else
    error("JSON parse error at position " .. i .. ": unexpected '" .. c .. "'")
  end
end

json = {
  parse_string = function(s, i)
    assert(s:sub(i, i) == "\"", "expected '\"' at position " .. i)
    i = i + 1
    local result = {}
    while i <= #s do
      local c = s:sub(i, i)
      if c == "\"" then
        return table.concat(result), i + 1
      elseif c == "\\" then
        local next_c = s:sub(i+1, i+1)
        if next_c == "n" then result[#result+1] = "\n"
        elseif next_c == "t" then result[#result+1] = "\t"
        elseif next_c == "r" then result[#result+1] = "\r"
        elseif next_c == "\"" then result[#result+1] = "\""
        elseif next_c == "\\" then result[#result+1] = "\\"
        elseif next_c == "/" then result[#result+1] = "/"
        elseif next_c == "u" then
          local hex = s:sub(i+2, i+5)
          local code = tonumber(hex, 16)
          if code < 128 then
            result[#result+1] = string.char(code)
          else
            if code < 2048 then
              result[#result+1] = string.char(192 + math.floor(code/64), 128 + code%64)
            else
              result[#result+1] = string.char(224 + math.floor(code/4096), 128 + math.floor(code/64)%64, 128 + code%64)
            end
          end
          i = i + 6
        else
          result[#result+1] = next_c
          i = i + 2
        end
      else
        result[#result+1] = c
        i = i + 1
      end
    end
    error("unterminated string")
  end,

  parse_number = function(s, i)
    local start = i
    if s:sub(i, i) == "-" then i = i + 1 end
    while i <= #s and s:sub(i, i):match("[0-9.eE+-]") do
      i = i + 1
    end
    local num_str = s:sub(start, i - 1)
    local n = tonumber(num_str)
    if not n then error("invalid number: " .. num_str) end
    return n, i
  end,

  parse_bool = function(s, i)
    if s:sub(i, i+3) == "true" then return true, i + 4
    elseif s:sub(i, i+4) == "false" then return false, i + 5
    else error("invalid boolean at position " .. i) end
  end,

  parse_null = function(s, i)
    if s:sub(i, i+3) == "null" then return nil, i + 4
    else error("invalid null at position " .. i) end
  end,

  parse_array = function(s, i)
    assert(s:sub(i, i) == "[", "expected '[' at position " .. i)
    i = i + 1
    local arr = {}
    i = skip_whitespace(s, i)
    if s:sub(i, i) == "]" then return arr, i + 1 end
    while true do
      local val
      val, i = parse_value(s, i)
      arr[#arr + 1] = val
      i = skip_whitespace(s, i)
      local c = s:sub(i, i)
      if c == "]" then return arr, i + 1
      elseif c == "," then i = i + 1
      else error("expected ',' or ']' at position " .. i) end
    end
  end,

  parse_object = function(s, i)
    assert(s:sub(i, i) == "{", "expected '{' at position " .. i)
    i = i + 1
    local obj = {}
    i = skip_whitespace(s, i)
    if s:sub(i, i) == "}" then return obj, i + 1 end
    while true do
      i = skip_whitespace(s, i)
      local key
      key, i = json.parse_string(s, i)
      i = skip_whitespace(s, i)
      assert(s:sub(i, i) == ":", "expected ':' at position " .. i)
      i = i + 1
      local val
      val, i = parse_value(s, i)
      obj[key] = val
      i = skip_whitespace(s, i)
      local c = s:sub(i, i)
      if c == "}" then return obj, i + 1
      elseif c == "," then i = i + 1
      else error("expected ',' or '}' at position " .. i) end
    end
  end,
}

