-- ─── stableStringify (same as capture) ───────────────────────────────────────
local function stable_stringify(val)
  if val == nil then return "null" end
  local t = type(val)
  if t == "string" then
    local escaped = val:gsub("\\", "\\\\"):gsub("\"", "\\\""):gsub("\n", "\\n"):gsub("\r", "\\r"):gsub("\t", "\\t")
    local function escape_control(s)
      local result = {}
      for i = 1, #s do
        local byte = s:byte(i)
        if byte < 0x20 then
          result[#result+1] = string.format("\\u%04x", byte)
        else
          result[#result+1] = s:sub(i, i)
        end
      end
      return table.concat(result)
    end
    escaped = escape_control(escaped)
    return "\"" .. escaped .. "\""
  elseif t == "number" then
    if val ~= val then return "\"__nan__\""
    elseif val == math.huge then return "\"__infinity__\""
    elseif val == -math.huge then return "\"__neg_infinity__\""
    end
    if val == math.floor(val) and math.abs(val) < 1e21 then
      return tostring(math.floor(val))
    else
      return tostring(val)
    end
  elseif t == "boolean" then
    return val and "true" or "false"
  elseif t == "table" then
    local is_array = true
    local max_index = 0
    local key_count = 0
    for k, _ in pairs(val) do
      key_count = key_count + 1
      if type(k) == "number" and k == math.floor(k) and k >= 1 then
        if k > max_index then max_index = k end
      else
        is_array = false
      end
    end
    if is_array and key_count == max_index then
      local parts = {}
      for i = 1, max_index do
        parts[i] = stable_stringify(val[i])
      end
      return "[" .. table.concat(parts, ",") .. "]"
    else
      local keys = {}
      for k, _ in pairs(val) do keys[#keys + 1] = tostring(k) end
      table.sort(keys)
      local parts = {}
      for _, k in ipairs(keys) do
        local v = val[k]
        parts[#parts + 1] = stable_stringify(k) .. ":" .. stable_stringify(v)
      end
      return "{" .. table.concat(parts, ",") .. "}"
    end
  end
  return "null"
end

