-- after JSON decode (strings → strings, numbers → numbers, arrays → tables).
-- This function is a no-op for the common case but could be extended for
-- type-coercion if needed.

local function coerce_input(val)
  return val  -- JSON decode already produces the right Lua types
end

-- ─── Invoke the entry function ───────────────────────────────────────────────
--   - If cluster.module is set: require(module) returns a table; look up entry on it
--   - Else: loadfile(file) and call it to get the module table, OR if the file
--     defines a global function, look it up in _G
--   - multiArgs: input must be an array; each element becomes one arg
--   - else: input is the sole arg (or nil if input is null)

local function invoke_entry(cluster, input)
  local fn
  if cluster.module then
    -- require() the module — package.path must include the project dir
    local ok, mod = pcall(require, cluster.module)
    if not ok then
      return nil, "require('" .. cluster.module .. "') failed: " .. tostring(mod)
    end
    fn = mod[cluster.entry]
    if type(fn) ~= "function" then
      return nil, "entry '" .. cluster.entry .. "' not found in module '" .. cluster.module .. "'"
    end
  elseif cluster.file then
    -- Load the file — it may define a global function or return a table
    local file_path = project_dir .. "/" .. cluster.file
    local chunk, err = loadfile(file_path)
    if not chunk then
      return nil, "loadfile('" .. file_path .. "') failed: " .. tostring(err)
    end
    -- Execute the chunk to define globals / get return value
    local ok, result = pcall(chunk)
    if not ok then
      return nil, "executing '" .. file_path .. "' failed: " .. tostring(result)
    end
    -- If the chunk returned a table, look up entry on it
    if type(result) == "table" and result[cluster.entry] then
      fn = result[cluster.entry]
    else
      -- Otherwise look up the global
      fn = _G[cluster.entry]
    end
    if type(fn) ~= "function" then
      return nil, "entry '" .. cluster.entry .. "' not found (neither in file return value nor _G)"
    end
  else
    return nil, "cluster has neither 'module' nor 'file' field"
  end

  -- Invoke the function
  local args
  if input == nil then
    args = {}
  elseif cluster.multiArgs and type(input) == "table" then
    args = input
  else
    args = {input}
  end
  local results = table.pack(pcall(fn, table.unpack(args)))
  local ok = results[1]
  if not ok then
    return nil, "function threw: " .. tostring(results[2])
  end
  -- Return first result (Lua functions can return multiple; we take the first)
  return results[2]
end

